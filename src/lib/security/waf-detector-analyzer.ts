/**
 * Web Application Firewall (WAF) & Edge Shield Detector (Inspirado no WAFW00F)
 * Inspeciona cabeçalhos, cookies e comportamento de resposta para identificar
 * firewalls de aplicação web e proxies reversos de proteção.
 */

export interface WafSignature {
  id: string;
  name: string;
  vendor: string;
  headerMatches?: Array<{ name: string; valuePattern?: RegExp }>;
  cookieMatches?: RegExp[];
  bodyMatches?: RegExp[];
  statusCodes?: number[];
}

export interface WafDetectionReport {
  targetUrl: string;
  detected: boolean;
  wafName: string;
  vendor: string;
  confidence: "HIGH" | "MEDIUM" | "LOW" | "NONE";
  detectionPhase: "PASSIVE" | "ACTIVE_PROBE" | "NONE";
  indicators: string[];
  recommendation: string;
  durationMs: number;
}

