export async function detectWaf(targetUrl: string): Promise<WafDetectionReport> {
  const startTime = Date.now();
  let url = targetUrl.trim();
  if (!url.startsWith("http://") && !url.startsWith("https://")) {
    url = `https://${url}`;
  }

  const indicators: string[] = [];
  let detectedWaf: WafSignature | null = null;
  let phase: "PASSIVE" | "ACTIVE_PROBE" | "NONE" = "NONE";
  let confidence: "HIGH" | "MEDIUM" | "LOW" | "NONE" = "NONE";

  // 1. FASE PASSIVA (Baseline Request)
  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 4000);

    const baselineRes = await fetch(url, {
      method: "GET",
      signal: controller.signal,
      redirect: "follow",
      headers: {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ObsidianSec/1.2",
        Accept: "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
      },
    });

    clearTimeout(timeout);

    const headers = baselineRes.headers;
    const rawSetCookies: string[] = [];
    if (typeof (headers as any).getSetCookie === "function") {
      rawSetCookies.push(...(headers as any).getSetCookie());
    } else {
      const sc = headers.get("set-cookie");
      if (sc) rawSetCookies.push(sc);
    }
    const cookieStr = rawSetCookies.join("; ");

    for (const waf of WAF_SIGNATURES) {
      // Checa headers
      if (waf.headerMatches) {
        for (const hm of waf.headerMatches) {
          const val = headers.get(hm.name);
          if (val !== null) {
            if (!hm.valuePattern || hm.valuePattern.test(val)) {
              indicators.push(`Cabeçalho identificador: '${hm.name}: ${val.slice(0, 50)}'`);
              detectedWaf = waf;
              confidence = "HIGH";
              phase = "PASSIVE";
            }
          }
        }
      }

      // Checa cookies
      if (waf.cookieMatches) {
        for (const cm of waf.cookieMatches) {
          if (cm.test(cookieStr)) {
            indicators.push(`Cookie exclusivo de WAF: padrão '${cm.source}'`);
            detectedWaf = waf;
            confidence = "HIGH";
            phase = "PASSIVE";
          }
        }
      }
    }
  } catch (err: any) {
    indicators.push(`Aviso na inspeção passiva: ${err.message}`);
  }

  // 2. FASE ATIVA BENIGNA (Se não foi conclusivo na fase passiva)
  if (!detectedWaf) {
    try {
      const parsed = new URL(url);
      parsed.searchParams.set("obsidian_waf_probe", "<script>alert('obsidiansec_probe')</script>");

      const probeController = new AbortController();
      const probeTimeout = setTimeout(() => probeController.abort(), 4000);

      const probeRes = await fetch(parsed.toString(), {
        method: "GET",
        signal: probeController.signal,
        headers: {
          "User-Agent": "ObsidianSec-WAF-Probe/1.2 (+https://obsidiansec.dev)",
        },
      });

      clearTimeout(probeTimeout);

      const status = probeRes.status;
      const body = await probeRes.text();
      const headers = probeRes.headers;

      if (status === 403 || status === 406 || status === 429 || status === 501) {
        for (const waf of WAF_SIGNATURES) {
          // Checa assinaturas de corpo HTML de bloqueio
          if (waf.bodyMatches) {
            for (const bm of waf.bodyMatches) {
              if (bm.test(body)) {
                indicators.push(`Padrão de bloqueio de WAF detectado no corpo da resposta: '${bm.source}'`);
                detectedWaf = waf;
                confidence = "HIGH";
                phase = "ACTIVE_PROBE";
                break;
              }
            }
          }
        }

        if (!detectedWaf) {
          detectedWaf = {
            id: "generic-waf",
            name: "Firewall / WAF Genérico (Bloqueio Detectado)",
            vendor: "Desconhecido / Provedor Customizado",
          };
          indicators.push(`A requisição de teste retornou HTTP ${status} (Bloqueio de ataque sintético).`);
          confidence = "MEDIUM";
          phase = "ACTIVE_PROBE";
        }
      }
    } catch {
      // Ignora falha na fase ativa
    }
  }

  const isDetected = detectedWaf !== null;
  const wafName = isDetected ? detectedWaf.name : "Nenhum WAF Detectado (Exposição Direta ao Servidor)";
  const vendor = isDetected ? detectedWaf.vendor : "Servidor Web Convencional";

  let recommendation = "WAF ativo e monitorando requisições de borda.";
  if (!isDetected) {
    recommendation = "Recomendado colocar a aplicação atrás de um WAF (ex: Cloudflare WAF, AWS WAF ou ModSecurity) para mitigar ataques automatizados de injeção SQL, XSS e botnets.";
  }

  return {
    targetUrl: url,
    detected: isDetected,
    wafName,
    vendor,
    confidence,
    detectionPhase: phase,
    indicators,
    recommendation,
    durationMs: Date.now() - startTime,
  };
}